import { Router } from 'express';
import { protect, requirePermission } from '../middleware/auth.js';
import * as g from '../controllers/governance.js';
const r = Router();
r.use(protect);
r.get('/notifications-realtime', requirePermission('notifications.view'), g.listNotifications);
r.patch('/notifications-realtime/:id/read', requirePermission('notifications.view'), g.markRead);
r.post('/notifications-realtime/read-all', requirePermission('notifications.view'), g.markAllRead);
r.get('/notification-preferences', g.getPreferences);
r.put('/notification-preferences', g.updatePreferences);
r.get('/audit-logs-pro', requirePermission('audit.view'), g.auditLogs);
r.get('/audit-logs-pro/export.csv', requirePermission('audit.view'), g.exportAudit);
r.get('/permissions', requirePermission('roles.view'), g.permissionList);
r.get('/roles', requirePermission('roles.view'), g.listRoles);
r.post('/roles', requirePermission('roles.create'), g.createRole);
r.put('/roles/:id', requirePermission('roles.update'), g.updateRole);
r.delete('/roles/:id', requirePermission('roles.delete'), g.deleteRole);
r.get('/users-access', requirePermission('users.view'), g.listUsers);
r.put('/users-access/:id', requirePermission('users.update'), g.assignRole);
export default r;
