import { RecurringJournal, JournalTemplate } from '../models/accounting.js';
import { JournalEntry } from '../models/accounting.js';
import { nextJournalNo, assertBalanced } from './postingEngine.js';
function nextDate(date, frequency) {
  const d = new Date(date);
  if (frequency === 'monthly') d.setMonth(d.getMonth() + 1);
  else if (frequency === 'quarterly') d.setMonth(d.getMonth() + 3);
  else d.setFullYear(d.getFullYear() + 1);
  return d;
}
let timer;
let running = false;
export async function runDueRecurringJournals() {
  if (running) return { processed: 0, created: 0, skipped: true };
  running = true;
  try {
    const now = new Date();
    const jobs = await RecurringJournal.find({ active: true, nextRunAt: { $lte: now } }).lean();
    let created = 0;
    for (const job of jobs) {
      const t = await JournalTemplate.findById(job.template);
      if (!t || !t.active) continue;
      const totals = assertBalanced(t.lines);
      await JournalEntry.create({
        journalNo: await nextJournalNo(),
        date: job.nextRunAt,
        type: t.type,
        narration: t.narration || t.name,
        status: 'draft',
        lines: t.lines,
        ...totals,
        createdBy: job.createdBy,
        approvalHistory: [{ action: 'updated', by: job.createdBy, reason: 'Generated by recurring journal scheduler' }],
        metadata: { recurringJournal: job._id, template: t._id },
      });
      const scheduledAt = job.nextRunAt;
      const followingRun = nextDate(scheduledAt, job.frequency);
      await RecurringJournal.updateOne(
        { _id: job._id, nextRunAt: scheduledAt },
        { $set: { lastRunAt: scheduledAt, nextRunAt: followingRun } },
      );
      created++;
    }
    return { processed: jobs.length, created };
  } finally {
    running = false;
  }
}
export function startRecurringJournalScheduler() {
  if (String(process.env.ACCOUNTING_RECURRING_ENABLED || 'true') !== 'true') return { enabled: false };
  const interval = Math.max(5, Number(process.env.ACCOUNTING_RECURRING_INTERVAL_MINUTES || 60)) * 60000;
  timer = setInterval(() => runDueRecurringJournals().catch(() => {}), interval);
  timer.unref?.();
  return { enabled: true, intervalMinutes: interval / 60000 };
}
export function stopRecurringJournalScheduler() {
  if (timer) clearInterval(timer);
  timer = null;
}
